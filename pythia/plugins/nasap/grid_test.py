import unittest
from grid import id_at, bounds_of_grid_tile, ids_in_square, BBox

class TestGrid(unittest.TestCase):
    def test_grid(self):
        """Test the grid system.
        A visualization of this test scenario can be found at "testfiles/nasap_grid.png" or
        https://www.figma.com/design/ykXqjwB9QcJKbU2R0nZNTu/GSSAT-Nasa-Grid?node-id=1-3&t=0JjjK9SYZvid968F-1
        """
        test_cases = [
            ("WSTA 1", id_at(-180, -90), -179.6875, -89.75),
            ("WSTA 2", id_at(-179.6875, -90), -179.0625, -89.75),
            ("WSTA 3", id_at(-179.0625, -90), -179, -89.75),
            ("WSTA 4", id_at(-179, -90), -178.4375, -89.75),
            ("WSTA 5", id_at(-178.4375, -90), -178, -89.75),
            ("WSTA 6", id_at(-178, -90), -177.8125, -89.75),
            ("WSTA 7", id_at(-177.8125, -90), -177.1875, -89.75),
            ("WSTA 8", id_at(-177.1875, -90), -177, -89.75),
        ]

        for name, id_val, expected_lon, expected_lat in test_cases:
            box = bounds_of_grid_tile(id_val)
            lon, lat = box.max_lon, box.max_lat
            center_lon, center_lat = box.centroid()

            assert id_val == id_at(center_lon, center_lat), (
                f"{name} center point ID mismatch"
            )
            assert abs(expected_lon - lon) < 1e-6, f"{name} longitude mismatch"
            assert abs(expected_lat - lat) < 1e-6, f"{name} latitude mismatch"


